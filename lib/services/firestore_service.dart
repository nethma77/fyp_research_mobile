import 'package:cloud_firestore/cloud_firestore.dart';
import '../models/driver_profile.dart';
import '../models/trip.dart';
import '../models/parking.dart';
import '../models/accident.dart';
import '../models/violation.dart';

class FirestoreService {
  final FirebaseFirestore _db = FirebaseFirestore.instance;

  // Generic method to fetch a list of items from a collection
  Future<List<T>> getCollection<T>({
    required String collectionPath,
    required T Function(Map<String, dynamic> data, String documentId) builder,
  }) async {
    try {
      final QuerySnapshot snapshot = await _db.collection(collectionPath).get();
      return snapshot.docs
          .map((doc) => builder(doc.data() as Map<String, dynamic>, doc.id))
          .toList();
    } catch (e) {
      print('Error fetching collection \$collectionPath: \$e');
      return [];
    }
  }

  // Generate Dummy Data for Testing
