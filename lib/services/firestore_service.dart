        await profileRef.set(DriverProfile(
          id: userId,
          name: 'John Doe',
          email: 'driver@test.com',
          vehicleType: 'Car',
          licenseNumber: 'DL123456789',
          rating: 4.8,
        ).toJson());
      }

      // 2. Trips
      await _db.collection('trips').add(Trip(
        id: '', // Will be generated by Firestore
        driverId: userId,
        startLocation: 'Point A',
        endLocation: 'Point B',
        startTime: DateTime.now().subtract(const Duration(days: 1)),
        endTime: DateTime.now().subtract(const Duration(hours: 23)),
        distance: 15.5,
